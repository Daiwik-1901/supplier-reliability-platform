"""Deterministic CSV / JSONL export of canonical tables, plus the dataset manifest.

Byte-for-byte reproducible on every OS (ruling R3):
- one ``<table>.csv`` and one ``<table>.jsonl`` per table, UTF-8 without BOM, ``\\n`` line
  endings (files are opened with ``newline=""`` and every line terminator is written explicitly);
- columns in model order; rows sorted by primary key in Python (so the order does not depend
  on the database collation);
- NULL -> empty CSV cell / JSON ``null``; Decimal -> fixed-point string with the column's scale
  (``"1234.50"``, ``format_decimal``: ROUND_HALF_UP, no exponent, zero unsigned). Values must
  already be quantised to the column scale at insert time (the generator does this). On SQLite,
  Numeric is stored as a binary float and SQLAlchemy's result processor turns it back into
  ``Decimal("%.<scale>f" % value)``, so read-back rounding happens there, not here;
  ``format_decimal`` only fixes the scale, the sign of zero and the notation.
  Datetimes -> ``YYYY-MM-DDTHH:MM:SS.ffffffZ`` (UTC); dates -> ``YYYY-MM-DD``; booleans ->
  ``true`` / ``false``; JSON columns -> canonical JSON (sorted keys,
  separators ``(",", ":")``) as text in CSV and as a nested value in JSONL.
- JSONL lines keep model column order (they are not key-sorted) and use the same separators.

The manifest's ``content_checksum`` is sha256 over the canonical JSON of the sorted
``[path, sha256]`` pairs only; ``execution_metadata`` (wall-clock and host facts) is excluded.
"""

import csv
import hashlib
import json
import platform
import socket
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import date, datetime
from decimal import ROUND_HALF_UP, Decimal
from enum import Enum
from importlib import metadata
from pathlib import Path
from typing import Any

import sqlalchemy as sa
from sqlalchemy.orm import Session

from supplier_reliability import GENERATOR_VERSION, SCHEMA_VERSION
from supplier_reliability.domain.numeric import ensure_utc
from supplier_reliability.models import Base
from supplier_reliability.services.generator.config import GeneratorConfig

__all__ = [
    "DEFAULT_EXPORT_TABLES",
    "PROVENANCE",
    "FileEntry",
    "build_manifest",
    "column_converter",
    "execution_metadata",
    "export_tables",
    "format_decimal",
    "write_csv",
]

_NOT_EXPORTED = frozenset({"dataset_jobs", "validation_runs", "validation_findings"})
DEFAULT_EXPORT_TABLES: tuple[str, ...] = tuple(
    t.name for t in Base.metadata.sorted_tables if t.name not in _NOT_EXPORTED
)
PROVENANCE = {"synthetic": True, "license": "MIT (synthetic data generated by this repository)"}
_DEPENDENCIES = ("numpy", "pandas", "faker", "sqlalchemy")
_EXECUTION_KEYS = frozenset(
    {"generated_at", "duration_seconds", "python_version", "dependency_versions", "hostname"}
)


@dataclass(frozen=True)
class FileEntry:
    path: str  # relative to the export directory, forward slashes
    rows: int
    sha256: str


def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def format_decimal(value: Decimal, scale: int) -> str:
    """Fixed-point string with exactly ``scale`` decimals (ROUND_HALF_UP), never scientific
    notation, and zero always unsigned (``-0.00`` -> ``0.00``) so every backend exports the
    same bytes."""
    q = Decimal(str(value)).quantize(Decimal(1).scaleb(-scale), rounding=ROUND_HALF_UP)
    if q.is_zero():
        q = q.copy_abs()
    return format(q, "f")


def column_converter(column: sa.Column) -> Any:
    """Per-column function: DB value -> JSON-ready value (str / bool / int / dict / None)."""
    ctype = column.type
    if isinstance(ctype, sa.Numeric) and not isinstance(ctype, sa.Float):
        scale = ctype.scale or 0
        return lambda v: format_decimal(v, scale)
    if isinstance(ctype, sa.JSON):
        return lambda v: json.loads(canonical_json(v))  # nested keys sorted
    return _scalar


def _scalar(v: Any) -> Any:
    if isinstance(v, bool | int):
        return v
    if isinstance(v, Enum):
        return v.value
    if isinstance(v, datetime):
        return ensure_utc(v).strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, str):
        return v
    raise TypeError(f"unsupported export value type {type(v).__name__}")


def _csv_cell(v: Any, is_json: bool) -> str:
    if v is None:
        return ""
    if is_json:
        return canonical_json(v)
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export_tables(
    session: Session, out_dir: Path, tables: Sequence[str] = DEFAULT_EXPORT_TABLES
) -> dict[str, FileEntry]:
    """Write ``<table>.csv`` and ``<table>.jsonl`` for each table; returns entries by path."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    entries: dict[str, FileEntry] = {}
    for name in tables:
        table = Base.metadata.tables[name]
        columns = list(table.columns)
        convert = [column_converter(c) for c in columns]
        is_json = [isinstance(c.type, sa.JSON) for c in columns]
        pk = [columns.index(c) for c in table.primary_key.columns]
        raw = [tuple(r) for r in session.execute(sa.select(*columns))]
        raw.sort(key=lambda r: tuple(r[i] for i in pk))
        rows = [[None if v is None else f(v) for v, f in zip(r, convert, strict=True)] for r in raw]
        header = [c.name for c in columns]

        csv_rows = [[_csv_cell(v, j) for v, j in zip(row, is_json, strict=True)] for row in rows]
        csv_entry = write_csv(out_dir, f"{name}.csv", header, csv_rows)
        jsonl_path = out_dir / f"{name}.jsonl"
        with jsonl_path.open("w", encoding="utf-8", newline="") as fh:
            for row in rows:
                line = json.dumps(
                    dict(zip(header, row, strict=True)),
                    separators=(",", ":"),
                    ensure_ascii=False,
                )
                fh.write(line + "\n")
        entries[csv_entry.path] = csv_entry
        rel = jsonl_path.relative_to(out_dir).as_posix()
        entries[rel] = FileEntry(rel, len(rows), _sha256(jsonl_path))
    return entries


def write_csv(
    out_dir: Path, rel_path: str, header: Sequence[str], rows: Sequence[Sequence[str]]
) -> FileEntry:
    """Write one CSV (UTF-8 without BOM, ``\\n`` line endings, csv-module quoting) of already
    formatted cells, in the given row order; returns its FileEntry (path relative to out_dir)."""
    out_dir = Path(out_dir)
    path = out_dir / rel_path
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)
    rel = path.relative_to(out_dir).as_posix()
    return FileEntry(rel, len(rows), _sha256(path))


def execution_metadata(generated_at: datetime | str, duration_seconds: float) -> dict[str, Any]:
    """Volatile facts about this run (never part of the content checksum)."""
    if isinstance(generated_at, datetime):
        generated_at = _scalar(generated_at)
    return {
        "generated_at": generated_at,
        "duration_seconds": duration_seconds,
        "python_version": platform.python_version(),
        "dependency_versions": {d: metadata.version(d) for d in _DEPENDENCIES},
        "hostname": socket.gethostname(),
    }


def content_checksum(entries: Mapping[str, FileEntry]) -> str:
    pairs = sorted([e.path, e.sha256] for e in entries.values())
    return hashlib.sha256(json.dumps(pairs, separators=(",", ":")).encode("utf-8")).hexdigest()


def build_manifest(
    cfg: GeneratorConfig,
    entries: Mapping[str, FileEntry],
    counts: Mapping[str, int],
    execution_meta: Mapping[str, Any],
) -> dict[str, Any]:
    missing = _EXECUTION_KEYS - set(execution_meta)
    if missing:
        raise ValueError(f"execution_meta lacks {sorted(missing)}")
    files = sorted(entries.values(), key=lambda e: e.path)
    return {
        "dataset_id": cfg.dataset_id,
        "seed": cfg.seed,
        "preset": cfg.preset,
        "generator_version": GENERATOR_VERSION,
        "schema_version": SCHEMA_VERSION,
        "config": json.loads(cfg.canonical_json()),
        "row_counts": dict(counts),
        "files": [{"path": e.path, "rows": e.rows, "sha256": e.sha256} for e in files],
        "content_checksum": content_checksum(entries),
        "provenance": dict(PROVENANCE),
        "execution_metadata": dict(execution_meta),
    }
